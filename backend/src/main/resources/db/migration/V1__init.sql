-- =====================================================================
-- SubFlow 1단계 핵심 스키마 (PostgreSQL 16)
-- =====================================================================
-- 설계 원칙
--  * 상태값은 varchar + CHECK 제약으로 고정한다(애플리케이션 enum과 이름을 일치시킨다).
--  * 시각은 모두 timestamptz(UTC)로 저장한다.
--  * 금액은 numeric(12,2). 통화는 ISO 4217 3자리.
--  * 멱등성은 DB 제약(유니크)으로 최후 방어한다:
--      payments.idempotency_key, webhook_inbox(pg_provider, event_id)
--  * 결제 원장(payments)은 한 번 승인 시도 = 한 행. 실패 후 재시도는 새 행 + payment_attempts 이력.
-- =====================================================================

-- ---------------------------------------------------------------------
-- 1) 구독 플랜
-- ---------------------------------------------------------------------
CREATE TABLE plans
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code          VARCHAR(50)    NOT NULL,
    name          VARCHAR(120)   NOT NULL,
    amount        NUMERIC(12, 2) NOT NULL,
    currency      VARCHAR(3)     NOT NULL DEFAULT 'KRW',
    billing_cycle VARCHAR(20)    NOT NULL,
    trial_days    INTEGER        NOT NULL DEFAULT 0,
    active        BOOLEAN        NOT NULL DEFAULT TRUE,
    description   VARCHAR(500),
    created_at    TIMESTAMPTZ    NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ    NOT NULL DEFAULT now(),
    CONSTRAINT uk_plans_code UNIQUE (code),
    CONSTRAINT ck_plans_amount CHECK (amount >= 0),
    CONSTRAINT ck_plans_trial_days CHECK (trial_days >= 0),
    CONSTRAINT ck_plans_billing_cycle CHECK (billing_cycle IN ('WEEKLY', 'MONTHLY', 'QUARTERLY', 'YEARLY'))
);

COMMENT ON TABLE plans IS '구독 상품(플랜). 가격·주기·체험 기간의 정의';
COMMENT ON COLUMN plans.trial_days IS '체험 일수. 0이면 체험 없이 즉시 결제';

-- ---------------------------------------------------------------------
-- 2) 고객
-- ---------------------------------------------------------------------
CREATE TABLE customers
(
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email        VARCHAR(255) NOT NULL,
    name         VARCHAR(100) NOT NULL,
    external_key VARCHAR(100),
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uk_customers_email UNIQUE (email),
    CONSTRAINT uk_customers_external_key UNIQUE (external_key)
);

COMMENT ON COLUMN customers.external_key IS '외부 서비스의 사용자 식별자. 없으면 NULL';
COMMENT ON TABLE customers IS '구독 고객. 이메일은 소문자로 정규화해 저장';

-- ---------------------------------------------------------------------
-- 3) 빌링키 (카드 원본 미보관, PG 토큰만)
-- ---------------------------------------------------------------------
CREATE TABLE billing_keys
(
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id       BIGINT       NOT NULL REFERENCES customers (id),
    pg_provider       VARCHAR(30)  NOT NULL,
    billing_key_token VARCHAR(255) NOT NULL,
    card_last4        VARCHAR(4),
    status            VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE',
    is_default        BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ck_billing_keys_status CHECK (status IN ('ACTIVE', 'INACTIVE', 'REVOKED')),
    CONSTRAINT ck_billing_keys_last4 CHECK (card_last4 IS NULL OR card_last4 ~ '^[0-9]{4}$')
);

-- 고객당 기본 빌링키는 1개 (부분 유니크 인덱스)
CREATE UNIQUE INDEX uk_billing_keys_default ON billing_keys (customer_id) WHERE is_default;
CREATE INDEX idx_billing_keys_customer ON billing_keys (customer_id);

COMMENT ON COLUMN billing_keys.billing_key_token IS 'PG가 발급한 빌링키. 외부 노출 금지(암호화 저장 권장)';
COMMENT ON COLUMN billing_keys.card_last4 IS '카드 표시용 마지막 4자리';

-- ---------------------------------------------------------------------
-- 4) 구독 (상태 머신의 중심)
-- ---------------------------------------------------------------------
CREATE TABLE subscriptions
(
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id          BIGINT      NOT NULL REFERENCES customers (id),
    plan_id              BIGINT      NOT NULL REFERENCES plans (id),
    billing_key_id       BIGINT REFERENCES billing_keys (id),
    status               VARCHAR(20) NOT NULL,
    current_period_start TIMESTAMPTZ NOT NULL,
    current_period_end   TIMESTAMPTZ NOT NULL,
    next_billing_at      TIMESTAMPTZ,
    retry_count          INTEGER     NOT NULL DEFAULT 0,
    cancel_at_period_end BOOLEAN     NOT NULL DEFAULT FALSE,
    canceled_at          TIMESTAMPTZ,
    version              BIGINT      NOT NULL DEFAULT 0,
    created_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_subscriptions_status CHECK (status IN ('TRIAL', 'ACTIVE', 'PAST_DUE', 'PAUSED', 'CANCELED', 'EXPIRED')),
    CONSTRAINT ck_subscriptions_period CHECK (current_period_end > current_period_start),
    CONSTRAINT ck_subscriptions_retry_count CHECK (retry_count >= 0)
);

-- 청구 배치가 훑는 경로: 청구 대상 상태 + 청구 시각 도래
CREATE INDEX idx_subscriptions_due ON subscriptions (next_billing_at)
    WHERE status IN ('TRIAL', 'ACTIVE', 'PAST_DUE');
CREATE INDEX idx_subscriptions_customer ON subscriptions (customer_id);
CREATE INDEX idx_subscriptions_status ON subscriptions (status);

COMMENT ON COLUMN subscriptions.next_billing_at IS '다음 청구 예정 시각(UTC). 해지·만료 시 NULL';
COMMENT ON COLUMN subscriptions.cancel_at_period_end IS '기간 종료 해지 예약. 기간이 끝나기 전까지 이용 가능';
COMMENT ON COLUMN subscriptions.version IS '낙관적 락 버전';

-- ---------------------------------------------------------------------
-- 5) 결제 원장
-- ---------------------------------------------------------------------
CREATE TABLE payments
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subscription_id BIGINT         NOT NULL REFERENCES subscriptions (id),
    idempotency_key VARCHAR(120)   NOT NULL,
    amount          NUMERIC(12, 2) NOT NULL,
    currency        VARCHAR(3)     NOT NULL DEFAULT 'KRW',
    status          VARCHAR(20)    NOT NULL,
    pg_provider     VARCHAR(30),
    pg_tx_id        VARCHAR(120),
    failure_code    VARCHAR(50),
    failure_reason  VARCHAR(500),
    paid_at         TIMESTAMPTZ,
    created_at      TIMESTAMPTZ    NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ    NOT NULL DEFAULT now(),
    CONSTRAINT uk_payments_idempotency_key UNIQUE (idempotency_key),
    CONSTRAINT ck_payments_status CHECK (status IN ('PENDING', 'SUCCEEDED', 'FAILED', 'CANCELED')),
    CONSTRAINT ck_payments_amount CHECK (amount >= 0)
);

CREATE INDEX idx_payments_subscription ON payments (subscription_id);
CREATE INDEX idx_payments_status ON payments (status);
CREATE INDEX idx_payments_paid_at ON payments (paid_at);

COMMENT ON COLUMN payments.idempotency_key IS '승인 멱등키(전역 유니크). 같은 키로 두 번 승인되지 않는다';
COMMENT ON COLUMN payments.paid_at IS '승인 성공 시각';

-- ---------------------------------------------------------------------
-- 6) 결제 시도 / Dunning 이력
-- ---------------------------------------------------------------------
CREATE TABLE payment_attempts
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_id    BIGINT      NOT NULL REFERENCES payments (id),
    attempt_no    INTEGER     NOT NULL,
    status        VARCHAR(20) NOT NULL,
    error_message VARCHAR(500),
    attempted_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uk_payment_attempts_payment_attempt UNIQUE (payment_id, attempt_no),
    CONSTRAINT ck_payment_attempts_status CHECK (status IN ('SUCCESS', 'FAILED')),
    CONSTRAINT ck_payment_attempts_no CHECK (attempt_no >= 1)
);

CREATE INDEX idx_payment_attempts_payment ON payment_attempts (payment_id);

COMMENT ON TABLE payment_attempts IS '결제 시도 이력. Dunning 재시도와 PG 응답 원문 보관';

-- ---------------------------------------------------------------------
-- 7) 수신 웹훅 멱등성 (inbox)
-- ---------------------------------------------------------------------
CREATE TABLE webhook_inbox
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pg_provider    VARCHAR(30)  NOT NULL,
    event_id       VARCHAR(120) NOT NULL,
    event_type     VARCHAR(80)  NOT NULL,
    payload        JSONB        NOT NULL,
    status         VARCHAR(20)  NOT NULL DEFAULT 'RECEIVED',
    received_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    processed_at   TIMESTAMPTZ,
    failure_reason VARCHAR(500),
    CONSTRAINT uk_webhook_inbox_provider_event UNIQUE (pg_provider, event_id),
    CONSTRAINT ck_webhook_inbox_status CHECK (status IN ('RECEIVED', 'PROCESSED', 'FAILED', 'IGNORED'))
);

CREATE INDEX idx_webhook_inbox_status ON webhook_inbox (status);

COMMENT ON TABLE webhook_inbox IS 'PG 웹훅 수신 보관함. (pg_provider, event_id) 유니크로 중복 수신 차단';
COMMENT ON COLUMN webhook_inbox.payload IS 'PG 원본 페이로드(가공 없이 보관)';

-- ---------------------------------------------------------------------
-- 8) Transactional Outbox
-- ---------------------------------------------------------------------
CREATE TABLE outbox_events
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aggregate_type VARCHAR(50)  NOT NULL,
    aggregate_id   VARCHAR(64)  NOT NULL,
    event_type     VARCHAR(80)  NOT NULL,
    payload        JSONB        NOT NULL,
    status         VARCHAR(20)  NOT NULL DEFAULT 'PENDING',
    retry_count    INTEGER      NOT NULL DEFAULT 0,
    next_retry_at  TIMESTAMPTZ,
    last_error     VARCHAR(500),
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    published_at   TIMESTAMPTZ,
    CONSTRAINT ck_outbox_events_status CHECK (status IN ('PENDING', 'PUBLISHED', 'FAILED')),
    CONSTRAINT ck_outbox_events_retry_count CHECK (retry_count >= 0)
);

CREATE INDEX idx_outbox_events_pending ON outbox_events (next_retry_at) WHERE status = 'PENDING';
CREATE INDEX idx_outbox_events_aggregate ON outbox_events (aggregate_type, aggregate_id);

COMMENT ON TABLE outbox_events IS '도메인 변경과 같은 트랜잭션으로 적재되는 발행 대기 이벤트';

-- ---------------------------------------------------------------------
-- 9) 정합성 점검 로그
-- ---------------------------------------------------------------------
CREATE TABLE reconciliation_logs
(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    target_date      DATE        NOT NULL,
    checked_count    INTEGER     NOT NULL DEFAULT 0,
    mismatch_count   INTEGER     NOT NULL DEFAULT 0,
    auto_fixed_count INTEGER     NOT NULL DEFAULT 0,
    summary          TEXT,
    executed_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_reconciliation_logs_counts CHECK (checked_count >= 0 AND mismatch_count >= 0
        AND auto_fixed_count >= 0 AND auto_fixed_count <= mismatch_count)
);

CREATE INDEX idx_reconciliation_logs_target_date ON reconciliation_logs (target_date);

COMMENT ON TABLE reconciliation_logs IS '일일 정합성 점검(PG 정산 대사, 청구 누락, 상태 불일치) 결과';
