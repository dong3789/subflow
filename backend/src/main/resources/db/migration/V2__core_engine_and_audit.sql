-- =====================================================================
-- SubFlow 2단계: 결제 코어 엔진 · 변경 이력 · 감사 로그 (PostgreSQL 16)
-- =====================================================================
-- 설계 원칙
--  * 1단계(V1) 테이블은 그대로 두고 필요한 컬럼만 더한다(운영 마이그레이션 안전).
--  * 멀티 프로젝트(오픈소스 SaaS)를 위해 projects 를 도입하고, 기존 도메인 테이블에
--    project_id 를 NULL 허용으로 붙인다(NULL = 기본 프로젝트). 기존 데이터는 그대로 유효하다.
--  * 외부 노출 식별자는 UUID(public_id)로 분리한다. 내부 PK(BIGINT)는 조인·성능용으로만 쓰고,
--    감사 로그(audit_logs.target_id)는 UUID 로 통일해 BIGINT/UUID 혼용을 막는다.
--  * 변경 이력은 before/after 스냅샷(JSONB)을 남겨 "언제 무엇이 어떻게 바뀌었는지"를 재구성할 수 있게 한다.
-- =====================================================================

-- ---------------------------------------------------------------------
-- 1) 프로젝트(테넌트/연동 단위) — 오픈소스 SaaS 의 최상위 격리 단위
-- ---------------------------------------------------------------------
CREATE TABLE projects
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id      UUID         NOT NULL DEFAULT gen_random_uuid(),
    name           VARCHAR(120) NOT NULL,
    api_key_prefix VARCHAR(30)  NOT NULL,
    api_key_hash   VARCHAR(128) NOT NULL,
    webhook_url    VARCHAR(500),
    webhook_secret VARCHAR(255),
    active         BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uk_projects_public_id UNIQUE (public_id),
    CONSTRAINT uk_projects_api_key_prefix UNIQUE (api_key_prefix)
);

CREATE UNIQUE INDEX uk_projects_api_key_hash ON projects (api_key_hash);
CREATE INDEX idx_projects_active ON projects (active);

COMMENT ON TABLE projects IS '프로젝트(테넌트). API Key 로 격리되고 자기 webhook_url 로 이벤트를 받는다';
COMMENT ON COLUMN projects.api_key_prefix IS 'pk_live_xxxx 처럼 로그·화면에 보여 줄 접두사';
COMMENT ON COLUMN projects.api_key_hash IS 'API Key 원문 대신 SHA-256 해시만 저장';
COMMENT ON COLUMN projects.webhook_secret IS 'Outbox 웹훅 HMAC-SHA256 서명 키';

-- 기본 프로젝트 시드: project_id 가 NULL 인 기존 데이터가 바라보는 기본 테넌트
INSERT INTO projects (name, api_key_prefix, api_key_hash, webhook_url, webhook_secret, active)
VALUES ('default', 'pk_default', encode(sha256('subflow-default-project-key'::bytea), 'hex'), NULL, NULL, TRUE);

-- ---------------------------------------------------------------------
-- 2) 플랜 보강: 외부 식별자·프로젝트 연결·주기 확장
-- ---------------------------------------------------------------------
ALTER TABLE plans
    ADD COLUMN public_id UUID NOT NULL DEFAULT gen_random_uuid(),
    ADD COLUMN project_id BIGINT REFERENCES projects (id);

ALTER TABLE plans ADD CONSTRAINT uk_plans_public_id UNIQUE (public_id);

-- WEEKLY/BIWEEKLY/FOUR_WEEKLY/MONTHLY/YEARLY 를 정식 지원한다(QUARTERLY 는 기존 데이터 호환용으로 유지).
ALTER TABLE plans DROP CONSTRAINT ck_plans_billing_cycle;
ALTER TABLE plans ADD CONSTRAINT ck_plans_billing_cycle
    CHECK (billing_cycle IN ('WEEKLY', 'BIWEEKLY', 'FOUR_WEEKLY', 'MONTHLY', 'QUARTERLY', 'YEARLY'));

CREATE INDEX idx_plans_project ON plans (project_id);
CREATE INDEX idx_plans_active ON plans (active) WHERE active;

-- ---------------------------------------------------------------------
-- 3) 고객 보강
-- ---------------------------------------------------------------------
ALTER TABLE customers
    ADD COLUMN public_id UUID NOT NULL DEFAULT gen_random_uuid(),
    ADD COLUMN project_id BIGINT REFERENCES projects (id);

ALTER TABLE customers ADD CONSTRAINT uk_customers_public_id UNIQUE (public_id);
CREATE INDEX idx_customers_project ON customers (project_id);

-- ---------------------------------------------------------------------
-- 4) 구독 보강: 기준일·누적 회차·중복 결제 가드·수량·해지 사유
-- ---------------------------------------------------------------------
ALTER TABLE subscriptions
    ADD COLUMN public_id UUID NOT NULL DEFAULT gen_random_uuid(),
    ADD COLUMN project_id BIGINT REFERENCES projects (id),
    ADD COLUMN billing_cycle VARCHAR(20),
    ADD COLUMN anchor_day INTEGER,
    ADD COLUMN billing_cycle_count INTEGER NOT NULL DEFAULT 0,
    ADD COLUMN last_billed_at TIMESTAMPTZ,
    ADD COLUMN cancel_reason VARCHAR(500),
    ADD COLUMN quantity INTEGER NOT NULL DEFAULT 1;

ALTER TABLE subscriptions ADD CONSTRAINT uk_subscriptions_public_id UNIQUE (public_id);
ALTER TABLE subscriptions ADD CONSTRAINT ck_subscriptions_anchor_day
    CHECK (anchor_day IS NULL OR (anchor_day >= 1 AND anchor_day <= 31));
ALTER TABLE subscriptions ADD CONSTRAINT ck_subscriptions_quantity CHECK (quantity >= 1);
ALTER TABLE subscriptions ADD CONSTRAINT ck_subscriptions_cycle_count CHECK (billing_cycle_count >= 0);
ALTER TABLE subscriptions ADD CONSTRAINT ck_subscriptions_billing_cycle
    CHECK (billing_cycle IS NULL OR billing_cycle IN ('WEEKLY', 'BIWEEKLY', 'FOUR_WEEKLY', 'MONTHLY', 'QUARTERLY', 'YEARLY'));

CREATE INDEX idx_subscriptions_project ON subscriptions (project_id);
CREATE INDEX idx_subscriptions_last_billed ON subscriptions (last_billed_at);

COMMENT ON COLUMN subscriptions.billing_cycle IS '플랜 주기 override. NULL 이면 플랜 주기를 따른다(주기 변경 시 사용)';
COMMENT ON COLUMN subscriptions.anchor_day IS '월 단위 주기의 기준일(1~31). 주 단위 주기에서는 NULL';
COMMENT ON COLUMN subscriptions.billing_cycle_count IS '누적 정상 결제 회차. 플랜 변경에도 유지된다';
COMMENT ON COLUMN subscriptions.last_billed_at IS '마지막 정상 결제 시각. 당일/보호 윈도우 중복 결제 가드에 쓴다';
COMMENT ON COLUMN subscriptions.quantity IS '구독 수량(좌석 수 등). 청구 금액 = 플랜 단가 × 수량';

-- ---------------------------------------------------------------------
-- 5) 결제 원장 보강
-- ---------------------------------------------------------------------
ALTER TABLE payments
    ADD COLUMN public_id UUID NOT NULL DEFAULT gen_random_uuid();

ALTER TABLE payments ADD CONSTRAINT uk_payments_public_id UNIQUE (public_id);

-- PG 거래 ID 로 웹훅/정합성 점검에서 원장을 찾는다(부분 유니크: 아직 승인 전이면 NULL).
CREATE UNIQUE INDEX uk_payments_pg_tx_id ON payments (pg_provider, pg_tx_id) WHERE pg_tx_id IS NOT NULL;

-- ---------------------------------------------------------------------
-- 6) 구독 변경 이력(before/after 스냅샷)
-- ---------------------------------------------------------------------
CREATE TABLE subscription_change_histories
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subscription_id BIGINT      NOT NULL REFERENCES subscriptions (id),
    change_type     VARCHAR(40) NOT NULL,
    before_state    JSONB       NOT NULL,
    after_state     JSONB       NOT NULL,
    effective_mode  VARCHAR(20) NOT NULL,
    reason          VARCHAR(500),
    actor_type      VARCHAR(20) NOT NULL,
    actor_id        VARCHAR(64),
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_sch_change_type CHECK (change_type IN
        ('PLAN_CHANGE', 'CYCLE_CHANGE', 'QUANTITY_CHANGE', 'BILLING_DATE_CHANGE', 'CANCEL', 'RESTORE')),
    CONSTRAINT ck_sch_effective_mode CHECK (effective_mode IN ('IMMEDIATE', 'NEXT_CYCLE')),
    CONSTRAINT ck_sch_actor_type CHECK (actor_type IN ('USER', 'ADMIN', 'SYSTEM'))
);

CREATE INDEX idx_sch_subscription ON subscription_change_histories (subscription_id, created_at DESC);
CREATE INDEX idx_sch_change_type ON subscription_change_histories (change_type);

COMMENT ON TABLE subscription_change_histories IS '플랜/주기/수량/결제일/해지 변경 이력. 해지·재생성 없이 같은 구독 안에서 변경을 추적한다';
COMMENT ON COLUMN subscription_change_histories.before_state IS '변경 직전 구독 스냅샷(JSONB)';
COMMENT ON COLUMN subscription_change_histories.after_state IS '변경 직후 구독 스냅샷(JSONB)';

-- ---------------------------------------------------------------------
-- 7) 감사 로그(누가 무엇을 바꿨는지)
-- ---------------------------------------------------------------------
CREATE TABLE audit_logs
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_type  VARCHAR(20) NOT NULL,
    actor_id    VARCHAR(64),
    target_type VARCHAR(40) NOT NULL,
    target_id   UUID        NOT NULL,
    action      VARCHAR(80) NOT NULL,
    metadata    JSONB       NOT NULL DEFAULT '{}'::jsonb,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_audit_logs_actor_type CHECK (actor_type IN ('USER', 'ADMIN', 'SYSTEM'))
);

CREATE INDEX idx_audit_logs_target ON audit_logs (target_type, target_id);
CREATE INDEX idx_audit_logs_actor ON audit_logs (actor_type, actor_id);
CREATE INDEX idx_audit_logs_created_at ON audit_logs (created_at DESC);

COMMENT ON TABLE audit_logs IS '감사 로그. target_id 는 UUID 로 통일해 BIGINT/UUID 혼용을 막는다';
COMMENT ON COLUMN audit_logs.actor_id IS '행위자 식별자(사용자/관리자 ID, 시스템이면 NULL)';
COMMENT ON COLUMN audit_logs.metadata IS '부가 정보(변경 전후 값, 요청 출처 등). 민감정보(카드·빌링키)는 담지 않는다';
